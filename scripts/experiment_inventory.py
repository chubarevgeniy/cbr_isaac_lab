#!/usr/bin/env python3
"""Generate a cross-worktree inventory of experiment logs and checkpoints.

The repository keeps large TensorBoard and checkpoint binaries out of Git.  Git
worktrees are stable enough to locate those files locally, so this script turns
that local state into a committed-friendly Markdown snapshot.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import subprocess
from pathlib import Path


CHECKPOINT_RE = re.compile(r"^agent_(\d+)\.pt$")


def git(*args: str) -> str:
    return subprocess.check_output(["git", *args], text=True).strip()


def worktrees() -> list[dict[str, str]]:
    lines = git("worktree", "list", "--porcelain").splitlines()
    result: list[dict[str, str]] = []
    current: dict[str, str] = {}
    for line in lines + [""]:
        if line.startswith("worktree "):
            if current:
                result.append(current)
            current = {"path": line.removeprefix("worktree ")}
        elif line.startswith("HEAD "):
            current["head"] = line.removeprefix("HEAD ")
        elif line.startswith("branch "):
            current["branch"] = line.removeprefix("branch refs/heads/")
        elif not line and current:
            result.append(current)
            current = {}
    return result


def checkpoint_key(path: Path) -> tuple[int, str]:
    match = CHECKPOINT_RE.match(path.name)
    return (int(match.group(1)), path.name) if match else (-1, path.name)


def run_rows(worktree: dict[str, str]) -> list[dict[str, object]]:
    root = Path(worktree["path"])
    runs_root = root / "logs" / "skrl" / "cbr_i_ppo"
    if not runs_root.is_dir():
        return []

    rows: list[dict[str, object]] = []
    for run_dir in sorted(path for path in runs_root.iterdir() if path.is_dir()):
        checkpoint_dir = run_dir / "checkpoints"
        checkpoints = sorted(
            (path for path in checkpoint_dir.glob("agent_*.pt") if path.is_file()),
            key=checkpoint_key,
        )
        best = checkpoint_dir / "best_agent.pt"
        if best.is_file():
            checkpoints.append(best)
        events = sorted(run_dir.glob("events.out.tfevents.*"))
        params = sorted(path.name for path in (run_dir / "params").glob("*.yaml"))
        rows.append(
            {
                "branch": worktree.get("branch", "detached"),
                "worktree": str(root),
                "run": str(run_dir),
                "checkpoints": [path.name for path in checkpoints],
                "events": len(events),
                "params": params,
            }
        )
    return rows


def supervisor_files(worktree: dict[str, str]) -> list[Path]:
    logs_root = Path(worktree["path"]) / "logs"
    if not logs_root.is_dir():
        return []
    return sorted(
        path
        for path in logs_root.rglob("*")
        if path.is_file()
        and (
            path.name == "status.json"
            or path.name in {"manifest.json", "supervisor.log", "supervisor-daemon.log"}
        )
    )


def markdown(repo_root: Path) -> str:
    records = worktrees()
    rows = [row for record in records for row in run_rows(record)]
    generated = dt.datetime.now().astimezone().isoformat(timespec="seconds")
    lines = [
        "# Полный локальный инвентарь экспериментов",
        "",
        "> Generated by `python scripts/experiment_inventory.py`; binaries are not committed.",
        "",
        f"Дата генерации: `{generated}`  ",
        f"Канонический worktree: `{repo_root}`",
        "",
        "## Git worktree",
        "",
        "| Branch | HEAD | Worktree | Logs |",
        "| --- | --- | --- | --- |",
    ]
    for record in records:
        root = Path(record["path"])
        logs = root / "logs"
        lines.append(
            f"| `{record.get('branch', 'detached')}` | `{record.get('head', '')[:12]}` "
            f"| `{root}` | {'yes' if logs.is_dir() else 'no'} |"
        )

    lines.extend(
        [
            "",
            "## PPO runs and checkpoints",
            "",
            "`Checkpoint names` перечисляет каждый найденный `agent_*.pt` и `best_agent.pt`.",
            "Путь к каталогу run можно сразу использовать как TensorBoard logdir.",
            "",
            "| Branch | Run directory | Events | Params | Checkpoint names |",
            "| --- | --- | ---: | --- | --- |",
        ]
    )
    if not rows:
        lines.append("| — | — | 0 | — | Логи не найдены |")
    else:
        for row in rows:
            checkpoints = ", ".join(f"`{name}`" for name in row["checkpoints"]) or "—"
            params = ", ".join(row["params"]) or "—"
            lines.append(
                f"| `{row['branch']}` | `{row['run']}` | {row['events']} | {params} | {checkpoints} |"
            )

    lines.extend(["", "## Supervisor status and manifests", ""])
    status_paths = [path for record in records for path in supervisor_files(record)]
    if not status_paths:
        lines.append("Файлы supervisor не найдены.")
    else:
        for path in status_paths:
            lines.append(f"- `{path}`")

    lines.extend(
        [
            "",
            "## TensorBoard",
            "",
            "Для просмотра всех найденных PPO runs из текущего worktree можно передать",
            "каталоги из таблицы в TensorBoard или собрать их shell-командой. Не",
            "переносите бинарные logs в Git.",
            "",
        ]
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("EXPERIMENT_INVENTORY.md"),
        help="Markdown output path (default: EXPERIMENT_INVENTORY.md)",
    )
    args = parser.parse_args()
    repo_root = Path(git("rev-parse", "--show-toplevel"))
    output = args.output if args.output.is_absolute() else repo_root / args.output
    output.write_text(markdown(repo_root), encoding="utf-8")
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
